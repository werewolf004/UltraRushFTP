//! Checksums of transferred files: SFV files (CRC32), `.md5` files, CRC32 and MD5 of a
//! local file.

use std::collections::HashMap;
use std::io::{self, Read};
use std::path::Path;

use md5::Digest;

/// Entries of an SFV file: name in lower case → CRC32. Comments (`;`) and unreadable lines
/// are ignored.
pub fn parse_sfv(text: &str) -> HashMap<String, u32> {
    text.lines()
        .map(str::trim)
        .filter(|l| !l.is_empty() && !l.starts_with(';'))
        .filter_map(|l| {
            let (name, crc) = l.rsplit_once(char::is_whitespace)?;
            let crc = u32::from_str_radix(crc.trim(), 16).ok()?;
            Some((name.trim().to_lowercase(), crc))
        })
        .collect()
}

/// Text of an SFV file for these (name, CRC32).
pub fn write_sfv(entries: &[(String, u32)]) -> String {
    let mut out = String::from("; Generated by UltraRushFTP\r\n");
    for (name, crc) in entries {
        out.push_str(&format!("{name} {crc:08X}\r\n"));
    }
    out
}

/// Text of an `.md5` file for these (name, MD5), in the `md5sum` format.
pub fn write_md5(entries: &[(String, [u8; 16])]) -> String {
    let mut out = String::new();
    for (name, sum) in entries {
        let hex: String = sum.iter().map(|b| format!("{b:02x}")).collect();
        out.push_str(&format!("{hex} *{name}\r\n"));
    }
    out
}

fn read_all(path: &Path, mut feed: impl FnMut(&[u8])) -> io::Result<()> {
    let mut f = std::fs::File::open(path)?;
    let mut buf = vec![0u8; 256 * 1024];
    loop {
        let n = f.read(&mut buf)?;
        if n == 0 {
            return Ok(());
        }
        feed(&buf[..n]);
    }
}

/// CRC32 of a local file.
pub fn file_crc32(path: &Path) -> io::Result<u32> {
    let mut h = crc32fast::Hasher::new();
    read_all(path, |b| h.update(b))?;
    Ok(h.finalize())
}

/// MD5 of a local file.
pub fn file_md5(path: &Path) -> io::Result<[u8; 16]> {
    let mut h = md5::Md5::new();
    read_all(path, |b| h.update(b))?;
    Ok(h.finalize().into())
}

/// Is this name an SFV file?
pub fn is_sfv(name: &str) -> bool {
    name.to_ascii_lowercase().ends_with(".sfv")
}

/// Expected CRC32 of `file` from the SFV files of its folder (the first one that lists it).
pub fn expected_crc(file: &Path) -> Option<u32> {
    let dir = file.parent()?;
    let name = file.file_name()?.to_string_lossy().to_lowercase();
    std::fs::read_dir(dir)
        .ok()?
        .flatten()
        .filter(|e| is_sfv(&e.file_name().to_string_lossy()))
        .filter_map(|e| std::fs::read(e.path()).ok())
        .find_map(|bytes| parse_sfv(&String::from_utf8_lossy(&bytes)).get(&name).copied())
}

/// Start of the name of the SFV status folder.
pub const SFV_STATUS_PREFIX: &str = "[UltraRushFTP] - ";

/// Name of the SFV status folder: `[UltraRushFTP] - ( 7 of 10 files OK = 70% ) -
/// INCOMPLETE`, with the bad files when there are some.
pub fn sfv_status_name(ok: usize, bad: usize, total: usize) -> String {
    let pct = (ok * 100).checked_div(total).unwrap_or(100);
    let state = if bad > 0 {
        "BAD FILES"
    } else if ok >= total {
        "COMPLETE"
    } else {
        "INCOMPLETE"
    };
    let bad = if bad > 0 { format!(", {bad} BAD") } else { String::new() };
    format!("{SFV_STATUS_PREFIX}( {ok} of {total} files OK{bad} = {pct}% ) - {state}")
}

/// Names (lower case) listed by the SFV files of a folder (`None`: no SFV file).
pub fn sfv_listed(dir: &Path) -> Option<std::collections::BTreeSet<String>> {
    let mut found = false;
    let mut names = std::collections::BTreeSet::new();
    for e in std::fs::read_dir(dir).ok()?.flatten().filter(|e| is_sfv(&e.file_name().to_string_lossy())) {
        found = true;
        if let Ok(bytes) = std::fs::read(e.path()) {
            names.extend(parse_sfv(&String::from_utf8_lossy(&bytes)).into_keys());
        }
    }
    found.then_some(names)
}

/// Replaces the SFV status folder of `dir` (empty folders named with
/// [`SFV_STATUS_PREFIX`]) with one named by [`sfv_status_name`].
pub fn write_sfv_status(dir: &Path, ok: usize, bad: usize, total: usize) -> io::Result<()> {
    let name = sfv_status_name(ok, bad, total);
    for e in std::fs::read_dir(dir)?.flatten() {
        let old = e.file_name().to_string_lossy().into_owned();
        if old.starts_with(SFV_STATUS_PREFIX) && old != name && e.path().is_dir() {
            // An emptied folder only: a folder the user filled is left alone.
            let _ = std::fs::remove_dir(e.path());
        }
    }
    let path = dir.join(name);
    if !path.is_dir() {
        std::fs::create_dir(path)?;
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn sfv_status_folder() {
        assert_eq!(sfv_status_name(7, 0, 10), "[UltraRushFTP] - ( 7 of 10 files OK = 70% ) - INCOMPLETE");
        assert_eq!(sfv_status_name(10, 0, 10), "[UltraRushFTP] - ( 10 of 10 files OK = 100% ) - COMPLETE");
        assert_eq!(sfv_status_name(8, 2, 10), "[UltraRushFTP] - ( 8 of 10 files OK, 2 BAD = 80% ) - BAD FILES");
        let dir = std::env::temp_dir().join(format!("urftp-sfv-status-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).unwrap();
        assert!(sfv_listed(&dir).is_none());
        std::fs::write(dir.join("rel.sfv"), "A.r00 00000001\r\na.r01 00000002\r\n").unwrap();
        assert_eq!(sfv_listed(&dir).unwrap().into_iter().collect::<Vec<_>>(), ["a.r00", "a.r01"]);
        write_sfv_status(&dir, 0, 0, 2).unwrap();
        write_sfv_status(&dir, 2, 0, 2).unwrap();
        let dirs: Vec<String> = std::fs::read_dir(&dir)
            .unwrap()
            .flatten()
            .filter(|e| e.path().is_dir())
            .map(|e| e.file_name().to_string_lossy().into_owned())
            .collect();
        assert_eq!(dirs, [sfv_status_name(2, 0, 2)], "the previous status folder is replaced");
        std::fs::remove_dir_all(&dir).unwrap();
    }

    #[test]
    fn sfv_md5_round_trip_and_file_sums() {
        let text = "; comment\r\nAlbum-01.mp3 1A2B3C4D\r\nwith space.r00   00000001\r\nbroken line\r\n";
        let m = parse_sfv(text);
        assert_eq!(m.get("album-01.mp3"), Some(&0x1A2B_3C4D));
        assert_eq!(m.get("with space.r00"), Some(&1));
        assert_eq!(m.len(), 2);
        assert_eq!(parse_sfv(&write_sfv(&[("A.bin".into(), 0xDEAD_BEEF)])).get("a.bin"), Some(&0xDEAD_BEEF));

        let dir = std::env::temp_dir().join(format!("urftp-sfv-{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        let f = dir.join("x.bin");
        std::fs::write(&f, b"123456789").unwrap();
        assert_eq!(file_crc32(&f).unwrap(), 0xCBF4_3926, "CRC32 check value");
        let md5 = file_md5(&f).unwrap();
        assert!(write_md5(&[("x.bin".into(), md5)]).starts_with("25f9e794323b453885f5181f1b624d0b *x.bin"));
        assert_eq!(expected_crc(&f), None);
        std::fs::write(dir.join("rel.SFV"), write_sfv(&[("X.BIN".into(), 0xCBF4_3926)])).unwrap();
        assert_eq!(expected_crc(&f), Some(0xCBF4_3926));
        assert!(is_sfv("a.Sfv") && !is_sfv("a.sfv.txt"));
        std::fs::remove_dir_all(&dir).unwrap();
    }
}
