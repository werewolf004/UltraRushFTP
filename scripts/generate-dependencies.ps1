# Generates the complete list of third-party crates compiled into UltraRushFTP for Windows
# (docs/dependencies-full.md) and, with -Notices, the licence texts that must ship with the
# binaries (THIRD-PARTY-LICENSES.txt). CI fails when the committed list is out of date.
#
#   pwsh scripts/generate-dependencies.ps1            # refresh docs/dependencies-full.md
#   pwsh scripts/generate-dependencies.ps1 -Notices   # also write THIRD-PARTY-LICENSES.txt
param([switch] $Notices)
$ErrorActionPreference = 'Stop'
Set-Location (Join-Path $PSScriptRoot '..')

$meta = cargo metadata --format-version 1 --locked --filter-platform x86_64-pc-windows-msvc | ConvertFrom-Json
$workspace = @{}
foreach ($id in $meta.workspace_members) { $workspace[$id] = $true }
$byId = @{}
foreach ($p in $meta.packages) { $byId[$p.id] = $p }

# Packages reachable from the workspace through normal (non-dev, non-build) dependencies.
$nodes = @{}
foreach ($n in $meta.resolve.nodes) { $nodes[$n.id] = $n }
$runtime = @{}
$stack = [System.Collections.Generic.Stack[string]]::new()
foreach ($id in $meta.workspace_members) { $stack.Push($id) }
while ($stack.Count -gt 0) {
    $id = $stack.Pop()
    foreach ($d in $nodes[$id].deps) {
        $normal = $d.dep_kinds | Where-Object { -not $_.kind }
        if ($normal -and -not $runtime.ContainsKey($d.pkg)) {
            $runtime[$d.pkg] = $true
            $stack.Push($d.pkg)
        }
    }
}

$rows = $meta.packages |
    Where-Object { -not $workspace.ContainsKey($_.id) } |
    Sort-Object name, version |
    ForEach-Object {
        $kind = if ($runtime.ContainsKey($_.id)) { 'runtime' } else { 'build/test' }
        $license = if ($_.license) { $_.license } else { "file: $($_.license_file)" }
        [pscustomobject]@{ Name = $_.name; Version = $_.version; License = $license; Kind = $kind; Repo = $_.repository; Dir = Split-Path $_.manifest_path }
    }

$lines = @(
    '<!-- Generated by scripts/generate-dependencies.ps1 — do not edit by hand. -->',
    '# Third-party crates / Crates tierces',
    '',
    "Total: $($rows.Count) — runtime (normal dependencies, Windows x64 / dépendances normales, Windows x64): $(@($rows | Where-Object Kind -eq 'runtime').Count); build/test = build scripts, proc macros of dev-dependencies, tests only.",
    '',
    '| Crate | Version | License / Licence | Use / Usage |',
    '|---|---|---|---|'
)
foreach ($r in $rows) { $lines += "| $($r.Name) | $($r.Version) | $($r.License) | $($r.Kind) |" }
($lines -join "`n") + "`n" | Set-Content -NoNewline -Encoding utf8NoBOM docs/dependencies-full.md
Write-Host "docs/dependencies-full.md: $($rows.Count) crates"

if ($Notices) {
    $out = [System.Text.StringBuilder]::new()
    [void]$out.AppendLine('Third-party software included in UltraRushFTP')
    [void]$out.AppendLine('==============================================')
    foreach ($r in ($rows | Where-Object Kind -eq 'runtime')) {
        [void]$out.AppendLine()
        [void]$out.AppendLine('-' * 78)
        [void]$out.AppendLine("$($r.Name) $($r.Version) — $($r.License)")
        if ($r.Repo) { [void]$out.AppendLine($r.Repo) }
        $files = Get-ChildItem -LiteralPath $r.Dir -File | Where-Object { $_.Name -match '^(LICEN[CS]E|COPYING|NOTICE)' }
        if (-not $files) { [void]$out.AppendLine("(no licence file in the package; licence: $($r.License))") }
        foreach ($f in $files) {
            [void]$out.AppendLine()
            [void]$out.AppendLine("[$($f.Name)]")
            [void]$out.AppendLine((Get-Content -LiteralPath $f.FullName -Raw))
        }
    }
    $out.ToString() | Set-Content -NoNewline -Encoding utf8NoBOM THIRD-PARTY-LICENSES.txt
    Write-Host 'THIRD-PARTY-LICENSES.txt written'
}
